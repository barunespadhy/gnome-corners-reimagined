def _hex_to_hls(hexval):
    r = int(hexval[0:2], 16) / 255.0
    g = int(hexval[2:4], 16) / 255.0
    b = int(hexval[4:6], 16) / 255.0
    return colorsys.rgb_to_hls(r, g, b)


def _hls_to_hex(h, l, s):
    r, g, b = colorsys.hls_to_rgb(h, l, s)
    return f"{round(r * 255):02x}{round(g * 255):02x}{round(b * 255):02x}"


def _luminance(hexval):
    r = int(hexval[0:2], 16) / 255.0
    g = int(hexval[2:4], 16) / 255.0
    b = int(hexval[4:6], 16) / 255.0
    return 0.299 * r + 0.587 * g + 0.114 * b


def accent_block(hexval):
    """Return a CSS @define-color block for the given 6-hex accent colour."""
    hexval = hexval.upper()
    h, _l, s = _hex_to_hls(hexval)
    fg = "ffffff" if _luminance(hexval) < 0.5 else "000000"
    return (f"@define-color accent_color #{hexval};\n"
            f"@define-color accent_bg_color #{hexval};\n"
            f"@define-color accent_fg_color #{fg};\n"
            f"@define-color blue_1 #{_hls_to_hex(h, 0.90, s)};\n"
            f"@define-color blue_2 #{_hls_to_hex(h, 0.74, s)};\n"
            f"@define-color blue_3 #{hexval};\n"
            f"@define-color blue_4 #{_hls_to_hex(h, 0.48, s)};\n"
            f"@define-color blue_5 #{_hls_to_hex(h, 0.30, s)};\n")

