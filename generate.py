def write(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    print("wrote", path)


def transform_shell(css, radius):
    """Replace the exact '4px' token in border-radius declarations."""
    def repl(m):
        value = m.group(1)
        tokens = [f"{radius}px" if t == "4px" else t for t in value.split()]
        return "border-radius: " + " ".join(tokens) + ";"
    return re.sub(r"border-radius:\s*([^;]+);", repl, css)


def transform_theme_value(val, radius):
    out = []
    for t in val.split():
        if t in ("0", "0px"):
            out.append(t)
        elif t.endswith("%"):
            out.append(t)
        elif re.fullmatch(r"-?\d+(\.\d+)?px", t):
            out.append(f"{radius}px")
        else:
            out.append(t)
    return " ".join(out)


def transform_theme_css(text, radius):
    return RADIUS_RE.sub(
        lambda m: m.group(1) + ": " + transform_theme_value(m.group(2), radius) + ";",
        text,
    )


def generate_gtk3_theme(radius, cfg, accent, home):
    """Rebuild the Radius4-dark GTK3 theme so GTK3 apps are uniformly themed."""
    if not os.path.exists(os.path.join(SRC_THEME, "gtk-3.0", "gtk.css")):
        print(f"adw-gtk3-dark not found at {SRC_THEME}; skipping GTK3 theme rebuild")
        return
    theme_dir = os.path.join(home, ".local", "share", "themes", "Radius4-dark")
    gtk3_dir = os.path.join(theme_dir, "gtk-3.0")
    os.makedirs(gtk3_dir, exist_ok=True)

    appended = f"""
/* Radius4 — keep genuine circles round */
avatar {{ border-radius: 9999px; -gtk-outline-radius: 9999px; }}
button.circular {{ border-radius: 9999px; -gtk-outline-radius: 9999px; }}
menubutton.circular > button {{ border-radius: 9999px; -gtk-outline-radius: 9999px; }}
indicatorbin > indicator, indicatorbin > mask {{ border-radius: 9999px; }}

/* exceptions: radio, switch and titlebar buttons use the radius */
radio {{ border-radius: {radius}px; }}
radio:checked {{ -gtk-icon-source: image(-gtk-recolor(url("file://{cfg}/gtk-3.0/radio-dot.svg"))); }}
switch {{ border-radius: {radius}px; }}
switch slider {{ border-radius: {radius}px; -gtk-outline-radius: {radius}px; }}
button.titlebutton,
button.titlebutton:not(.appmenu),
.default-decoration.titlebar:not(headerbar) button.titlebutton,
headerbar.default-decoration button.titlebutton {{ border-radius: {radius}px; -gtk-outline-radius: {radius}px; }}
"""

    def finish(text):
        return (transform_theme_css(text, radius) + "\n\n" + appended + "\n\n"
                + accent.rstrip("\n") + "\n")

    for name in ("gtk.css", "libadwaita.css"):
        src = open(os.path.join(SRC_THEME, "gtk-3.0", name)).read()
        write(os.path.join(gtk3_dir, name), finish(src))

    # gtk-dark.css is identical to gtk.css in adw-gtk3-dark
    write(os.path.join(gtk3_dir, "gtk-dark.css"),
          finish(open(os.path.join(SRC_THEME, "gtk-3.0", "gtk.css")).read()))

    shutil.copy2(os.path.join(SRC_THEME, "gtk-3.0", "libadwaita-tweaks.css"),
                 os.path.join(gtk3_dir, "libadwaita-tweaks.css"))

    assets_dst = os.path.join(gtk3_dir, "assets")
    if os.path.isdir(assets_dst):
        shutil.rmtree(assets_dst)
    shutil.copytree(os.path.join(SRC_THEME, "gtk-3.0", "assets"), assets_dst)

    gtk4_dir = os.path.join(theme_dir, "gtk-4.0")
    os.makedirs(gtk4_dir, exist_ok=True)
    for name in ("gtk.css", "gtk-dark.css"):
        shutil.copy2(os.path.join(SRC_THEME, "gtk-4.0", name),
                     os.path.join(gtk4_dir, name))

    index = """[Desktop Entry]
Type=X-GNOME-Metatheme
Name=Radius4-dark
Comment=Border-radius theme (generated by GnomeCornersReimagined)
Encoding=UTF-8

[X-GNOME-Metatheme]
GtkTheme=Radius4-dark
MetacityTheme=Radius4-dark
ButtonLayout=close,minimize,maximize:
"""
    write(os.path.join(theme_dir, "index.theme"), index)


def apply_dashtodock(radius, home):
    """Set the Dash-to-Dock dock background radius to the chosen radius."""
    candidates = [
        os.path.join(home, ".local", "share", "gnome-shell", "extensions",
                     "dash-to-dock@micxgx.gmail.com", "stylesheet.css"),
        "/usr/share/gnome-shell/extensions/dash-to-dock@micxgx.gmail.com/stylesheet.css",
    ]
    path = next((p for p in candidates if os.path.exists(p)), None)
    if not path:
        print("dash-to-dock stylesheet not found; skipping")
        return

    backup = path + ".bak-gcr"
    if not os.path.exists(backup):
        shutil.copy2(path, backup)

    css = open(path).read()
    # dock background radii are the only positive integer px radii
    # (24px/18px originally, or a previously-applied Npx); 0 / 0px / 1em kept.
    css = re.sub(r"border-radius:\s*([1-9][0-9]*)px;",
                 f"border-radius: {radius}px;", css)
    write(path, css)


def main():
    args = sys.argv[1:]
    radius = 4
    apply_dtd = False
    accent = "orange"  # Ubuntu default accent

    i = 0
    while i < len(args):
        a = args[i]
        if a in ("--dashtodock", "-dtd"):
            apply_dtd = True
            i += 1
        elif a in ("--accentcolour", "--accent-color", "--accent", "-ac"):
            if i + 1 >= len(args):
                print("Error: missing value for --accentcolour", file=sys.stderr)
                sys.exit(1)
            accent = args[i + 1]
            i += 2
        else:
            try:
                radius = int(a)
            except ValueError:
                pass
            i += 1

    key = accent.lower()
    if key in ACCENTS:
        hexval = ACCENTS[key]
    elif re.fullmatch(r"[0-9a-fA-F]{6}", accent):
        hexval = accent
    else:
        print(f"Error: unknown accent colour '{accent}'. "
              f"Use one of {', '.join(sorted(ACCENTS))} or a 6-digit hex "
              f"(without '#').", file=sys.stderr)
        sys.exit(1)
    accent_css = accent_block(hexval)

    home = os.path.expanduser("~")
    cfg = os.path.join(home, ".config")
    here = os.path.dirname(os.path.abspath(__file__))

    gtk4 = (GTK4_TEMPLATE
            .replace("__RADIUS__", str(radius))
            .replace("__CFG__", cfg)
            .replace("__ACCENT__", accent_css))
    gtk3 = (GTK3_TEMPLATE
            .replace("__RADIUS__", str(radius))
            .replace("__CFG__", cfg)
            .replace("__ACCENT__", accent_css))

    write(os.path.join(cfg, "gtk-4.0", "gtk.css"), gtk4)
    write(os.path.join(cfg, "gtk-4.0", "gtk-dark.css"), gtk4)
    write(os.path.join(cfg, "gtk-3.0", "gtk.css"), gtk3)
    write(os.path.join(cfg, "gtk-3.0", "gtk-dark.css"), gtk3)

    write(os.path.join(cfg, "gtk-4.0", "radio-dot.svg"), RADIO_DOT_SVG)
    write(os.path.join(cfg, "gtk-3.0", "radio-dot.svg"), RADIO_DOT_SVG)

    generate_gtk3_theme(radius, cfg, accent_css, home)

    if apply_dtd:
        apply_dashtodock(radius, home)

    theme_dir = os.path.join(
        home, ".local", "share", "themes", "Radius4", "gnome-shell")
    for src_name, dst_name in (("stylesheet.css", "gnome-shell.css"),
                               ("stylesheet-light.css", "gnome-shell-light.css")):
        src_path = os.path.join(here, src_name)
        if os.path.exists(src_path):
            css = open(src_path).read()
            write(os.path.join(theme_dir, dst_name), transform_shell(css, radius))

    print(f"GnomeCornersReimagined: applied {radius}px radius, accent #{hexval}")


if __name__ == "__main__":
    main()
